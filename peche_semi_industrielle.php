                    <p>

                      La pêche semi-industrielle est une activité pratiquée à une échelle intermédiaire entre la pêche artisanale et la pêche industrielle, au moyen d’embarcations et d’équipements adaptés. Elle nécessite des investissements et une organisation plus importante que la pêche artisanale, tout en restant de dimension plus limitée que la pêche industrielle. Elle permet ainsi d’accroître la production halieutique tout en favorisant une exploitation responsable et durable des ressources aquatiques.

A l’origine, la pêche semi-industrielle en RDC était très active dans les lacs Tanganyika, Edouard, Albert et Moëro. Elle a connu son développement jusqu’en 1970. A l’époque, sa production atteignait 25.000 à 30.000 tonnes/an. Elle revêtait une grande importance par rapport à son apport à la production nationale de poisson.


                    </p>

                     <p>

                     Ce sous-secteur a connu un déclin depuis les mesures de zaïrianisation de 1973 qui ont été à l’origine de la détérioration de l’outil de production. En 1974, les entreprises grecques se sont orientées vers les activités de commercialisation qui requièrent des investissements modestes et dégagent des marges plus importantes. La décadence de la pêche semi-industrielle est consécutive à la mauvaise gestion, à une mauvaise organisation du travail et à un entretien défectueux du matériel.

Les ruptures d’approvisionnement en carburant et en pièces détachées, et la pénurie de matériel de pêche ont été citées parmi les principales contraintes du secteur semi-industriel.

