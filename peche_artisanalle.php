                    <p>

                      La pêche artisanale est une activité pratiquée à petite ou moyenne échelle, principalement au moyen d’embarcations de petite taille et d’engins de pêche simples. Elle repose généralement sur des techniques traditionnelles et mobilise une main-d’œuvre importante, notamment au sein des communautés riveraines.
Elle joue un rôle essentiel dans l’approvisionnement des marchés locaux, la création d’emplois et les revenus des ménages. Sa pratique doit s’inscrire dans une gestion responsable des ressources aquatiques afin de préserver les stocks de poissons et les écosystèmes pour les générations futures.

                    </p>

                     <p>

                    En RDC pêcheries artisanales et coutumières constituent l’essentiel des activités des pêches et concernent plus de 90 % de quantités pêchées. Les unités de pêche artisanale sont constituées pour la plupart de pirogues monoxyles (rivières, mares intérieures, zones marécageuses, etc) ou en planche (cas de lacs de l’Est du pays) de 4 à 6 mètres de long et propulsées soit à l’aide de pagaie, soit de moteurs. Le taux de motorisation des pirogues est très faible.

Les principaux engins de pêche utilisés sont des filets maillants, les sennes, les palangres, les nasses et les éperviers, et le rendement de ces engins sont estimés peu satisfaisants. Les filets maillants dérivants de fond et de surface et les sennes tournantes et de plage sont utilisés dans la pêche qualifiée de professionnelle tandis que les éperviers, les palangres, les nasses et les filets dormants sont couramment utilisés dans la petite pêche dite non-professionnelle.

