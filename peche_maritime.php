                    <p>

                     La pêche artisanale maritime est une activité pratiquée à petite ou moyenne échelle dans les eaux maritimes, principalement au moyen de petites embarcations et d’engins de pêche adaptés. Elle repose sur des techniques généralement simples et mobilise une main-d’œuvre importante, notamment au sein des communautés côtières. Elle joue un rôle important dans l’approvisionnement des marchés locaux, la création d’emplois et la génération de revenus pour les communautés riveraines. 

La pêche artisanale maritime se pratique le long de la côte atlantique congolaise qui s’étend du Cabinda au nord à l’embouchure du Fleuve Congo du sud sur un peu plus de 35 km, et elle inclut aussi l’estuaire du fleuve Congo. Près de 4.000 pêcheurs pratiquant les activités de pêche. Ces pêcheurs utilisent des pirogues monoxyles de fabrication locale, longues de 6 à 9 mètres, propulsées soit par des pagaies, soit à la voile et soit à moteur hors-bord dont la puissance varie entre 5 et 40 CV, le taux de motorisation est de l’ordre 9 %. 

                    </p>

                     <p>

                  La capture totale de la pêche artisanale maritime est estimée à 1.200 tonnes par an et composée essentiellement de requin blanc (42%), carangue (11%) Bonite (20%) Bar (9%), Capitaine (5%), Raie (4%), sole (2%) Perche (3%) et Congre (2%).
Les principaux sites de débarquement sont : N’siamfumu, Moanda, et Banana pour la cote Atlantique et Banana, Kimwabi et Fumukilembe pour l’estuaire du Fleuve Congo.

