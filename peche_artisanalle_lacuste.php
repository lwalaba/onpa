                    <p>
La pêche lacustre en République démocratique du Congo est une pêche continentale typique.
</p>
<h2>Lac Tanganyika</h2>
                     <p>

               Les activités de pêche au Lac Tanganyika sont notamment : la pêche commerciale exercée par les pêcheurs tant industriels qu’artisanaux, la pêche de subsistance ainsi que le prélèvement des poissons d’ornement pour exportation.</p>
<p>La pêche artisanale au Lac Tanganyika est réalisée au moyen des pirogues en bois dont la plupart ne sont pas motorisées. Ces pirogues sont équipées de 3 à 12 lampes à gaz ou à pétrole et elles sont dirigées, selon les cas, par deux ou quatre pêcheurs. Parfois les pirogues sont reliées par des perches en bois et on parle de Catamarans conduits par quatre pêcheurs et équipés de 6 à 12 lampes à gaz ou à pétrole et d’un filet carrelet (lifte-net).</p>
<p>Le poisson frais du lac Tanganyika au niveau de Kalemie se vend uniquement sur le marché de Kalemie et le proche voisinage. Sa distribution ne dépasse pas 50 km autour de Kalemie. Le Marché local étant restreint, la majeure partie de la production est destinée aux provinces du Kasai, du Kivu et du Sud Katanga. Plus d’une centaine de commerçants viennent à Kalemie pour acheter du poisson séché et salé-séché pour approvisionner les villes de Mwene-Ditu (67%), Kananga (32%) et Lubumbashi (1%).</p>

   <h2>Au lac Edouard</h2>
        
   <p>
    La pêche artisanale au lac Edouard est pratiquée au moyen des pirogues en planche qui se déplacent, soit à la rame assistée de voiles primitives, soit à l’aide de moteurs hors-bord (6-8 CV)</p>
<p>Les principales méthodes de pêche pratiquées sont la pêche au filet dormant, la pêche à la senne de plage et la pêche à la senne tournante. L’utilisation de cette dernière technique a été expérimentée dans la partie sud du lac par la Coopérative de Pêcheries de Virunga (COPEVI).</p>
<p>Les filets sont normalement fabriqués sur place avec les fils achetés en contrebande en Ouganda. Le prix élevé et la rareté du matériel représentent la contrainte la plus importante pour le développement de la pêche artisanale de ce plan d’eau. Les deux principaux centres de pêche sont : Vitshumbi et Kyavinyonge.

 <h2>Au Lac Albert</h2>

 <p>
    Le potentiel halieutique du Lac Albert est estimé entre 21.000 et 30.000 tonnes dont 9.700 à 13.300 tonnes pour la partie congolaise. La productivité naturelle du lac Albert serait de 30 à 40 kg/ha/an. </p>
<p>Les activités de la pêche sont la pêche de subsistance et la pêche artisanale. La pêche de subsistance est réalisée au moyen de pirogues monoxyles non motorisés équipées de palangrottes, de palangres et de filets maillants tandis que la pêche artisanale utilise les barques propulsées à l’aviron, parfois au moteur, ce qui leur permet d’accéder à des zones moins fréquentées et d’obtenir de meilleurs rendements.  </p>
<p>La production consiste principalement en espèces prédatrices : Alestes bamerose, Hydrocynus forskahli et Lates niloticus albertinus. Les autres espèces d’intérêt sont les Tilapia, Hydrocyon goliath et Bagrus ubangensis. 
</p><p> Kasengyi et Mahagi Port sont les principaux sites de débarquement de produits de pêche sur le lac Albert. </p>

 <h2>Lac Moëro</h2>

 <p>
    Le nombre de pêcheurs du secteur artisanal du lac Moëro est d’environ 16.800 utilisant des pirogues monoxyles et des filets maillants dormants, les palangres et des nasses comme engins de pêche. Les principaux sites de débarquement sont : Pweto, Kilwa, Kasenga et Kashiobwe.
 </p> 
 <p>
    La production est estimée à 18.370 tonnes par an et elle est composée de Tilapia macrochir (environ 80 %), de Clarias, de Synodontis, de Barbus altivelis et de Mormyridae. Les techniques principales de transformation du poisson au lac Moëro sont le salage-séchage et le fumage.

 </p>

  <h2>Lac Kivu </h2>

  <p>
    Le potentiel de production annuelle du lac tout entier est estimé entre 11.300 tonnes et 30.000 tonnes par an, correspondant à un potentiel pour la partie congolaise de 7.000 à 19.000 tonnes par an. Ces estimations sont très incertaines sans une étude hydro biologique. On estime que la productivité naturelle du lac serait de 80 à 180kg/ha/an.
  </p>
  <p>
    La faune du lac Kivu est pauvre en espèces. Les espèces principales sont les suivantes : Barilius ubangensis, Barbus, Clarias, Tilapia et Haplochromis. 
    Les principaux centres de pêche artisanale se sont développés entre Goma et Bukavu, tels que Nzula, Minova, Kahele, Katana et Kazingo.

    Compte tenu de l’importance des populations riveraines et de la faible production actuelle l’écoulement du poisson ne pose pas de problèmes, la majorité des captures étant vendue dans les marchés locaux.
 
    Les infrastructures du froid existantes devraient être remises en état pour améliorer leur efficacité.
  </p>

  

