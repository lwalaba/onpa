                    <p>

                      La pêche industrielle est une activité de pêche pratiquée à grande échelle au moyen de navires et d’équipements spécialisés. Elle permet d’assurer une production importante de produits halieutiques tout en nécessitant une gestion responsable des ressources et le respect des normes de pêche durable.

La pêche industrielle existait avant 1990 et concernait exclusivement la pêche maritime le long de la côte Atlantique congolaise qui s’étend sur 42 Km, du Cabinda au Nord à l’embouchure du Fleuve Congo au Sud. Le plateau continental de la RDC s’étend de la limite extérieure de la zone économique exclusive, à 101,58 miles marins sur la limite latérale Sud et à 104,28 miles marins sur la limite latérale Nord. (Commission des limites du plateau continental, Mai 2009).


                    </p>

                     <p>

                      La pêche industrielle comprenait quatre unités en exploitation dont deux d’environ 50 m de long équipées d’un système de congélation à bord dont un appartenant à la société Pêcheries Maritimes du Congo (PEMARCO) et l’autre à la société Pêcherie Industrielle de Moanda (PMI).

Compte tenu du faible niveau des ressources maritimes de la ZEE congolaise (estimées à 4.000 T/an), la pêche industrielle maritime ne pouvait se développer que si elle étendait ses activités dans les eaux voisines dans le cadre des accords préférentiels de pêche. En 1985, une première expérience a été tentée en signant un accord provisoire avec l’Angola pour une pêche expérimentale qui aurait dû se concrétiser dans un accord de pêche définitif pour un certain nombre de bateaux congolais. Mais, malheureusement, ces accords n’ont pas abouti.
La pêche industrielle concernait les espèces démersales, semi-démersales et pélagiques destinées au marché local. Les quantités limitées de poissons pélagiques (notamment des sardinelles) ne justifiaient pas des investissements importants pour leur exploitation. Par contre, les espèces démersales et semi-démersales sont beaucoup plus riches.
La ville portuaire de Matadi possède un port de pêche et des installations de conservation.


