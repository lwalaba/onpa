                    <p>
Les agences de financement extérieures interviennent dans ce secteur par le biais des projets et programmes qu’elles financent. Les projets phares en cours intervenant dans le secteur de pêche sont : 

 </p>
 <br>
 <p>Programme d’urgence d’autosuffisance alimentaire (PUAA) élaboré par le Gouvernement congolais en 2002 suite aux guerres civiles qui se sont succédées et ont occasionné le déplacement des populations rurales vers les grands centres urbains. Le montant du programme est de deux milliards de francs congolais par année pour une durée de cinq ans. L’objectif principal fait partie d’une série de mesures prises par le Gouvernement pour contribuer à la sécurité alimentaire et à la lutte contre la pauvreté, par la production des denrées alimentaires de base en qualité et en quantité suffisantes et en les rendant accessibles et disponibles sur le marché. 

 </p>
 <br>
 <p>Programme de relance de l’agriculture dans la province de l’Equateur (PRAPE) validé en avril 2003 par le gouvernement dans la province de l’Equateur, et plus spécialement dans le territoire de Bumba et dans l’hinterland de Mbandaka, a pour but de Contribuer à l’amélioration de la sécurité alimentaire et des conditions de vie des ménages ruraux. Son objectif opérationnel est de Restaurer et améliorer l’accès durable et équitable des ménages ruraux, notamment les couches déshéritées aux moyens d’existence durable. Initié et financé par le Fonds international de développement Agricole (FIDA) Fonds Belge de Survie (FBS), le PRAPE comprend quatre composantes opérationnelles, à savoir : Composante A- Recapitalisation et relance de l’économie agricole ; Composante B- Recapitalisations et Relance de l’économie halieutique ; Composante C-Restauration et amélioration de l’accès des communautés aux services sociaux de base. La composante D est alors décidée à la Gestion du Programme.  

 </p>
 <br>
 <p>Programme de relance de l’agriculture dans la Province  Orientale (PRAPO) a pour objectifs de contribuer de manière durable à l’augmentation des revenus, de la sécuritaire alimentaire, de l’état nutritionnel et à l’amélioration des conditions de vie des populations ciblées, ainsi qu’à une gestion plus durable des ressources naturelles. Les couts totaux du programme sont estimés à 26,15 millions USD, financés par le Fonds international de développement agricole (FIDA), le Fonds de survie belge, la coopération du Royaume Uni (DFID), la contrepartie de la RDC et la participation des bénéficiaires. Le programme comprend quatre composantes : Relance de l’agriculture, de l’élevage et de la pêche ; Accès aux marchés et appui à la commercialisation ; Accès aux services sociaux de base ; Coordination et gestion du programme.

 </p>
 <br>
 <p>Projet de pêche artisanale et aquaculture au Katanga   (PPAK) et région annexe est financé par la Coopération technique belge pour un montant de 5.000.000 €. Ce projet a pour objectif global de contribuer à la sécuritaire alimentaire et à la réduction de la pauvreté, en réhabilitant le secteur de la pêche et la pisciculture par : (i) l’exploitation durable des ressources halieutiques en milieux lacustres au Katanga et (i) le développement de l’élevage de poissons en étangs dans les sites sélectionnés. Ce projet se développe principalement au Katanga avec une nette prépondérance pour la pêche vu les ressources piscicoles naturelles importantes. Une composante pisciculture est également envisagée dans la région de Lubumbashi et de Kinshasa vu la multitude d’étangs en essais de production.
   
 </p>
 <br>
 <p>Programme régional pour l’aménagement intégré du lac Tanganyika (PRODAP). Ce programme régional qui couvre les quatre pays riverains du lac s’articule autour de quatre domaines thématiques majeurs et d’une composante opérationnelle/ de gestion : (i) appui institutionnel et renforcement des capacités qui comprend la création de l’Autorité du lac, l’harmonisation de la législation sur les pêches et l’environnement ainsi que l’élaboration et la mise en œuvre d’un programme régional de surveillance de pêches et de l’environnement ; l’aménagement des pêches qui a pour objectif la conservation durable des pêches et des écosystèmes par l’élaboration et la mise en œuvre de mesures conjointes d’aménagement, la mise en place de zones protégées, l’éducation sur l’environnement, la formation et les activités de vulgarisation et les services communautaires en milieu rural ; (iii) développement des pêches et des infrastructures /qui vise la valorisation de la pêche autour du lac par l’amélioration de la qualité des produits grâce à la formation, la sensibilisation, l’installation infrastructures et de matériels de transport essentiels et à la création de fonds de développement local ; (iv)   contre la pollution et préservation de l’environnement qui concerne les interventions prioritaires identifiées car les membres dans les domaines de l’aménagement des bassins versants et/ou du traitement des eaux. Cette composante inclut les initiatives relatives à la gestion des terres et des eaux et aux systèmes agricoles dans les bassins hydrologiques. Aussi les activités de conservation du sol, la lutte contre la    sédimentation, l’amélioration du traitement des eaux usées et l’atténuation des effets de pesticides et des engrais.
 </p><br>
 <p>A l’exception du projet artisanal et aquaculture au Katanga qui est un projet totalement sectoriel, les quatre autres sont des projets et programmes multisectoriels comprenant une composante (volet) pêche.

 


</p>

    



